/**
 * THE DRESSING ROOM (owner, 13.10.2026: "a talk before and after every match — four answers, and they change the players'
 * morale"). Pure, no imports beyond the hash. The bank is the contract:
 *  · a SITUATION is read from the match in front of the manager — before: the opponent's strength, the table gap, home or
 *    away, the run of form, a top-of-the-table clash, the last result, the season's stage; after: the result, the margin, a late
 *    goal, a comeback or a lead thrown away, red cards, the move in the table, the title race, the foot of the table
 *  · every situation has four answers, always in the same four tones (calm · demanding · praise · fire), and the RIGHT tone
 *    depends on the moment: praise after a heavy loss lands badly, fire before an opening day of nerves can boil over
 *  · the pick is deterministic: the most specific situations that match, then one of them by `hash(seed)` — so a reload or a
 *    replay is the same talk, word for word
 *  · nobody real is quoted: the lines are the manager's own (the fan's), and the reaction is the ROOM, never a named man's words
 * The effect is a mood step (−0.5…+0.5) for the room and, for some answers, for a group of men (the scorers, the eleven, the
 * bench, a man sent off). `morale.ts` bounds it, `engine.ts` reads it as at most ±2.5%.
 */
export type Tone='calm'|'demand'|'praise'|'fire'
export const TONES:readonly Tone[]=['calm','demand','praise','fire']
export const TONE_TEXT:Record<Tone,string>={calm:'Calm',demand:'Demanding',praise:'Praise',fire:'Fire them up'}
export type Target='xi'|'bench'|'scorers'|'reds'
export type Answer={tone:Tone;line:string;reaction:string;team:number;men?:{who:Target;d:number}}
export type Result='W'|'D'|'L'
/** what the manager's club knows at the moment of the talk — built by `career.ts` from the career, nothing else */
