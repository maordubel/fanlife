/** the situation for one moment: the most specific that match, then one of them by the seed — the same seed, the same talk */
export function pickSituation(c:TalkCtx,seed:string):Situation{
 const pool=BANK.filter(s=>s.when===c.when&&s.test(c)),top=Math.max(...pool.map(s=>s.tier)),best=pool.filter(s=>s.tier===top)
 return best[hash(seed)%best.length]!
}
