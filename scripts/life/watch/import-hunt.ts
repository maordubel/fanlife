/**
 * LIFE · the watch layer — import the owner's highlights hunt (24.11.2026).
 *
 *   npx tsx scripts/life/watch/import-hunt.ts [--check]
 *
 * Reads `docs/life/highlights/hunt-2026-11-24-audited.md` (the file the owner sent back, every row checked against
 * its match: same teams, same score, the date or season, footage, embeddable — see `audit-report-2026-11-24.md`) and
 * writes `lib/life/watch/hunt.ts`. A link with no `?` is a checked match film and is served; a link ending in `?`
 * still has one open check and is kept aside in HUNT_PENDING (never served); NONE is a row searched without a find.
 * `--check` writes nothing and exits 1 when the file on disk differs.
 */
import {readFileSync, writeFileSync} from 'node:fs'

const SRC = 'docs/life/highlights/hunt-2026-11-24-audited.md'
const OUT = 'lib/life/watch/hunt.ts'
type Row = {clubId: string; factId: string; on: string; title: string; youtubeId: string; part: 'a' | 'b'; chapter: string | null}

export function parseHunt(md: string): {verified: Row[]; pending: Row[]; none: number} {
  const verified: Row[] = [], pending: Row[] = []
  let club = '', part: 'a' | 'b' = 'a', none = 0
  for (const line of md.split('\n')) {
    const h = line.match(/^## .+ · `([a-z0-9-]+)`/); if (h) { club = h[1]; continue }
    if (line.startsWith('**חלק א')) part = 'a'
    if (line.startsWith('**חלק ב')) part = 'b'
    const cells = line.split('|').map(c => c.trim())
    if (cells.length < 8 || !cells[1].startsWith('`')) continue
    const factId = cells[1].replace(/`/g, ''), on = cells[2], title = cells[3].replace(/\s*ℹ️\s*$/, ''), link = cells[6]
    if (link === 'NONE' || !link) { none++; continue }
    const m = link.match(/youtube\.com\/watch\?v=([A-Za-z0-9_-]{11})(\s*\?)?\s*$/)
    if (!m) throw new Error(`${club} ${factId}: unreadable link "${link}"`)
    const chapter = part === 'a' ? (cells[4].match(/^([a-z-]+)/)?.[1] ?? null) : null
    ;(m[2] ? pending : verified).push({clubId: club, factId, on, title, youtubeId: m[1], part, chapter})
  }
  return {verified, pending, none}
}

function render(v: Row[], p: Row[]): string {
  const q = (s: string) => JSON.stringify(s)
  const line = (r: Row, status: string) => `  {kind: 'highlights', id: ${q(r.factId)}, clubId: ${q(r.clubId)}, youtubeId: ${q(r.youtubeId)}, title: ${q(r.title)}, titleLocale: 'en', matchDate: ${q(r.on)}, chapter: ${r.chapter ? q(r.chapter) : 'null'}, status: '${status}', summary: true, source: {file: SRC, note: ${q(`hunt row ${r.factId} (part ${r.part}); checked against the match in the audit of 24.11.2026`)}}},`
  return `/**
 * GENERATED by scripts/life/watch/import-hunt.ts from ${SRC} — do not edit by hand.
 * HUNT_VERIFIED: match films checked row by row (teams, score, date or season, footage, embeddable). Served.
 * HUNT_PENDING: a match with one check still open. Kept aside, never served, until a later hunt clears it.
 */
import type {HighlightsMoment} from './types'

const SRC = ${q(SRC)}

export const HUNT_VERIFIED: readonly HighlightsMoment[] = [
${v.map(r => line(r, 'verified')).join('\n')}
]

export const HUNT_PENDING: readonly HighlightsMoment[] = [
${p.map(r => line(r, 'optional')).join('\n')}
]
`
}

if (process.argv[1]?.endsWith('import-hunt.ts')) {
  const {verified, pending, none} = parseHunt(readFileSync(SRC, 'utf8'))
  const text = render(verified, pending)
  if (process.argv.includes('--check')) {
    const cur = (() => { try { return readFileSync(OUT, 'utf8') } catch { return '' } })()
    if (cur !== text) { console.error(`${OUT} is stale — run the import`); process.exit(1) }
  } else writeFileSync(OUT, text)
  console.log(`verified ${verified.length} · pending ${pending.length} · none ${none}`)
}
