// pxl's own key view of each keepsake sprite (outline included) → the token rows PixelSprite paints.
//   node scripts/life/sprites/export-keeps.mjs
import {execFileSync} from 'node:child_process'
import {writeFileSync} from 'node:fs'
import {homedir} from 'node:os'

const PXL = `${homedir()}/.cache/claude-tools/pxl/bin/pxl.js`, FILE = 'scripts/life/sprites/keeps.px.js'
const names = ['shirt', 'ticket', 'note', 'pin', 'key', 'album', 'coins']
const out = {}
for (const n of names) {
  const txt = execFileSync('node', [PXL, 'ascii', FILE, n], {encoding: 'utf8'})
  const rows = txt.split('\n').map(l => l.match(/^\s*\d+ ([.kcwsnm]+)$/)?.[1]).filter(Boolean)
  if (!rows.length || rows.some(r => r.length !== rows[0].length)) throw new Error(`${n}: unreadable`)
  out[n] = rows
}
const body = Object.entries(out).map(([n, rows]) => `  ${n}: [\n${rows.map(r => `    '${r}',`).join('\n')}\n  ],`).join('\n')
writeFileSync('components/clubs/life/pixelKeeps.ts', `/**
 * GENERATED by scripts/life/sprites/export-keeps.mjs from scripts/life/sprites/keeps.px.js (pxl) — do not edit by hand.
 * The keepsake stickers, in LIFE tokens (c club · k ink · w paper · s ground · n deep · m mark).
 */
export const KEEP_SPRITES = {
${body}
} as const
`)
console.log(Object.keys(out).join(' '))
