// The kit drawings are served from fixed paths that Cloudflare keeps for a day (and serves stale for a week), so a redrawn
// shirt reached nobody (17.11.2026: the Hapoel 1999/00 fix was live and the edge still sent the old stripes). Every <img> of a
// kit drawing carries ?v=KIT_ART_VERSION — one hash of every shipped drawing — so a changed drawing is a new URL at once.
//   node scripts/kits/stamp-kit-art-version.mjs        (export-kit-svgs.mjs runs it after every export; tests/clubs/kit-art-version.test.ts checks it)
import {readFileSync,readdirSync,writeFileSync,existsSync} from 'node:fs'
import {createHash} from 'node:crypto'
import {pathToFileURL} from 'node:url'
export function kitArtVersion(root='public/club-kits'){
 const h=createHash('sha1')
 for(const club of readdirSync(root).sort()){const dir=`${root}/${club}/svg`;if(!existsSync(dir))continue
  for(const f of readdirSync(dir).filter(f=>f.endsWith('.svg')).sort()){h.update(`${club}/${f}\n`);h.update(readFileSync(`${dir}/${f}`))}}
 return h.digest('hex').slice(0,10)
}
export function stamp(){
 const v=kitArtVersion()
 writeFileSync('lib/clubs/kit-art-version.ts',`/** Generated by scripts/kits/stamp-kit-art-version.mjs — a hash of every shipped kit drawing, appended to their URLs. */\nexport const KIT_ART_VERSION='${v}'\n`)
 return v
}
if(import.meta.url===pathToFileURL(process.argv[1]).href)console.log('kit art version',stamp())
